"""Score every orchestrator run against the artist's joints (runs/reference.json) and write runs/SCORES.md.

A run's joints come from its choices.json. Each reference joint is matched by at most one run joint with
the same type and sides (a slide's direction; a hinge's side and opening direction). Joint limits are not
compared: they come from the sweep, not from a choice.

  python tools/score.py
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def key(joint: dict) -> tuple:
    if joint["type"] == "slide":
        return ("slide", joint["direction"])
    return ("hinge", joint["hinge"], "top" if joint["opens"] in ("up", "top") else joint["opens"])


def score(run: Path, reference: dict) -> dict | None:
    choices_path, proof_path = run / "choices.json", run / "proof.json"
    if not choices_path.exists():
        return None
    choices = json.loads(choices_path.read_text(encoding="utf-8"))
    proof = json.loads(proof_path.read_text(encoding="utf-8")) if proof_path.exists() else {}
    name = choices["name"]
    if name not in reference:
        return None
    wanted = [key(j) for j in reference[name]["joints"]]
    got = [key(j) for j in choices["joints"].values()]
    matched, left = 0, list(got)
    for joint in wanted:
        if joint in left:
            left.remove(joint)
            matched += 1
    sweep = json.loads((run / "sweep.json").read_text(encoding="utf-8"))
    return {"run": run.name, "prop": name, "split": proof.get("split", {}).get("source", "?"),
            "parts": sum(len(g["nodes"]) for g in sweep["groups"]), "groups": len(sweep["groups"]),
            "open": sum(g["decision"] == "choose" for g in sweep["groups"]),
            "decided_by": json.loads((run / "decisions.json").read_text(encoding="utf-8"))["decided_by"]
            if (run / "decisions.json").exists() else "-",
            "reference": len(wanted), "matched": matched, "extra": len(left),
            "joints": ", ".join(" ".join(k) for k in got) or "none",
            "self_test": proof.get("self_test_passed"), "fallbacks": proof.get("fallbacks_used", [])}


def main() -> int:
    sys.stdout.reconfigure(errors="backslashreplace")
    reference = json.loads((ROOT / "runs" / "reference.json").read_text(encoding="utf-8"))["props"]
    rows = [r for r in (score(p, reference) for p in sorted((ROOT / "runs").iterdir()) if p.is_dir()) if r]
    lines = ["| Run | Split by | Parts → groups (open) | Decided by | Joints found | Matches the artist | Extra | Self-test |",
             "|---|---|---|---|---|---|---|---|"]
    for r in rows:
        lines.append(f"| {r['run']} | {r['split']} | {r['parts']} → {r['groups']} ({r['open']}) | {r['decided_by']} | "
                     f"{r['joints']} | **{r['matched']} of {r['reference']}** | {r['extra']} | "
                     f"{'PASS' if r['self_test'] else 'FAIL' if r['self_test'] is False else '-'} |")
    table = "\n".join(lines)
    (ROOT / "runs" / "SCORES.md").write_text(
        "# Scores against the artist\n\nGenerated by `tools/score.py` from each run's `choices.json` and "
        "`runs/reference.json`.\n\n" + table + "\n", encoding="utf-8")
    print(table)
    return 0


if __name__ == "__main__":
    sys.exit(main())
